export type OsColor = (typeof DEFS)[number][0];

const POOL = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789!@#$%^&*()-=+[]{};:,<>/?~_|';

/** 색 이름 → 팔레트 문자 */
export const O = {} as Record<OsColor, string>;
/** 팔레트 문자 → hex */
export const OSPAL: Record<string, string> = {};
DEFS.forEach(([name, hex], i) => {
  const ch = POOL[i];
  if (!ch) throw new Error('os palette pool exhausted');
  O[name] = ch;
  OSPAL[ch] = hex;
});

