export type DeskColor = (typeof DEFS)[number][0];

const POOL = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789!@#$%^&*()-=+[]{};:,<>/?~_|';
// 이름이 한 글자 대문자인 항목(G,H,I...)은 풀 글자와 충돌하지 않도록 이름→문자 매핑을 따로 둔다.
/** 색 이름 → 팔레트 문자 */
export const D = {} as Record<DeskColor, string>;
/** 팔레트 문자 → hex */
export const DESKPAL: Record<string, string> = {};
DEFS.forEach(([name, hex], i) => {
  const ch = POOL[i];
  if (!ch) throw new Error('desk palette pool exhausted');
  D[name] = ch;
  DESKPAL[ch] = hex;
});

